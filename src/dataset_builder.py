def validate_dataset(df: pd.DataFrame) -> bool:
    """
    Validate and display statistics for the GACS dataset.

    Checks for required columns, missing values, and provides
    summary statistics about mood words.

    Args:
        df: GACS dataset DataFrame

    Returns:
        True if validation passes, False otherwise
    """
    print("\n" + "="*70)
    print("Dataset Validation")
    print("="*70)

    # Check required columns
    required_cols = ['image_id', 'video_id', 'scene_id', 'keyframe_path',
                     'mood_vector', 'mood_words', 'style_words', 'object_words']
    missing_cols = [c for c in required_cols if c not in df.columns]
    if missing_cols:
        logger.error(f"Missing required columns: {missing_cols}")
        return False

    # Basic stats
    print(f"\nTotal entries: {len(df)}")
    print(f"Unique videos: {df['video_id'].nunique()}")
    print(f"Unique scenes: {df['scene_id'].nunique()}")

    # Check for missing values
    print("\nMissing values:")
    has_missing = False
    for col in required_cols:
        missing = df[col].isna().sum()
        if missing > 0:
            print(f"  {col}: {missing}")
            has_missing = True
    if not has_missing:
        print("  None")

    # Mood word frequency
    print("\nTop 20 mood words:")
    all_mood_words = []
    for words in df['mood_words']:
        all_mood_words.extend([w.strip() for w in words.split(',')])

    mood_counts = pd.Series(all_mood_words).value_counts().head(20)
    print(mood_counts.to_string())

    logger.info("Dataset validation complete")
    return True


