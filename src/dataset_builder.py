def encode_image_base64(image_path: Path) -> str:
    """
    Encode an image file to base64 for Claude API.

    Args:
        image_path: Path to the image file

    Returns:
        Base64-encoded image data as string

    Raises:
        FileNotFoundError: If image file does not exist
        IOError: If unable to read image file
    """
    with open(image_path, "rb") as f:
        return base64.standard_b64encode(f.read()).decode("utf-8")


def get_image_media_type(image_path: Path) -> str:
    """
    Get MIME media type from image file extension.

    Args:
        image_path: Path to the image file

    Returns:
        MIME media type string (e.g., "image/jpeg")
    """
    ext = image_path.suffix.lower()
    media_types = {
        '.jpg': 'image/jpeg',
        '.jpeg': 'image/jpeg',
        '.png': 'image/png',
        '.gif': 'image/gif',
        '.webp': 'image/webp'
    }
    return media_types.get(ext, 'image/jpeg')


def call_claude_vision(client: anthropic.Anthropic,
                       image_path: Path,
                       prompt: str,
                       max_retries: int = 3) -> Optional[str]:
    """
    Call Claude Vision API with an image and prompt.

    Implements exponential backoff for rate limit errors (429).
    Logs warnings for transient errors and returns None on failure after retries.

    Args:
        client: Initialized Anthropic API client
        image_path: Path to the image file
        prompt: Text prompt to send along with the image
        max_retries: Maximum number of retry attempts (default 3)

    Returns:
        Response text from Claude, or None if all attempts failed

    Raises:
        No exceptions raised; failures are logged and None is returned
    """
    for attempt in range(max_retries):
        try:
            image_data = encode_image_base64(image_path)
            media_type = get_image_media_type(image_path)

            message = client.messages.create(
                model=CLAUDE_MODEL,
                max_tokens=256,
                messages=[
                    {
                        "role": "user",
                        "content": [
                            {
                                "type": "image",
                                "source": {
                                    "type": "base64",
                                    "media_type": media_type,
                                    "data": image_data
                                }
                            },
                            {
                                "type": "text",
                                "text": prompt
                            }
                        ]
                    }
                ]
            )

            return message.content[0].text.strip()

        except anthropic.RateLimitError:
            wait = 2 ** attempt * API_RATE_LIMIT_DELAY
            if attempt < max_retries - 1:
                logger.warning(f"Rate limited, waiting {wait}s "
                              f"(attempt {attempt + 1}/{max_retries})")
                time.sleep(wait)
        except anthropic.APIError as e:
            logger.error(f"API error on attempt {attempt + 1}: {e}")
            if attempt < max_retries - 1:
                time.sleep(API_RATE_LIMIT_DELAY)
        except Exception as e:
            logger.error(f"Unexpected error: {e}")
            if attempt < max_retries - 1:
                time.sleep(API_RATE_LIMIT_DELAY)

    logger.error(f"Failed to get response after {max_retries} attempts")
    return None


def parse_comma_list(text: str) -> List[str]:
    """
    Parse comma-separated response into a list of cleaned items.

    Splits on commas, strips whitespace, converts to lowercase,
    and removes empty items.

    Args:
        text: Comma-separated text response from API

    Returns:
        List of cleaned items
    """
    if not text:
        return []
    items = [item.strip().lower() for item in text.split(',')]
    items = [item for item in items if item]
    return items


def validate_labels(mood_words: List[str],
                    style_words: List[str],
                    object_words: List[str]) -> List[str]:
    """
    Validate that label counts match specification.

    Specification:
        - mood_words: exactly 5
        - style_words: exactly 3
        - object_words: 3-5

    Args:
        mood_words: List of mood adjectives
        style_words: List of style descriptors
        object_words: List of object nouns

    Returns:
        List of validation issue strings (empty if valid)
    """
    issues = []
    if len(mood_words) != 5:
        issues.append(f"Expected 5 mood words, got {len(mood_words)}")
    if len(style_words) != 3:
        issues.append(f"Expected 3 style words, got {len(style_words)}")
    if not (3 <= len(object_words) <= 5):
        issues.append(f"Expected 3-5 object words, got {len(object_words)}")
    return issues


def load_annotation(image_id: str) -> Optional[Annotation]:
    """
    Load annotation from cache if it exists.

    Checks data/annotations/{image_id}.json and deserializes
    the JSON into an Annotation object.

    Args:
        image_id: Image identifier to look up

    Returns:
        Annotation object if found, None otherwise
    """
    annotation_path = ANNOTATIONS_DIR / f"{image_id}.json"
    if annotation_path.exists():
        try:
            with open(annotation_path, 'r') as f:
                data = json.load(f)
            return Annotation(**data)
        except Exception as e:
            logger.warning(f"Failed to load annotation {image_id}: {e}")
    return None


def save_annotation(annotation: Annotation) -> Path:
    """
    Save annotation to data/annotations/{image_id}.json.

    Serializes the Annotation dataclass to JSON with indentation.

    Args:
        annotation: Annotation object to save

    Returns:
        Path to the saved annotation file
    """
    annotation_path = ANNOTATIONS_DIR / f"{annotation.image_id}.json"
    try:
        with open(annotation_path, 'w') as f:
            json.dump(asdict(annotation), f, indent=2)
        logger.debug(f"Saved annotation to {annotation_path}")
        return annotation_path
    except Exception as e:
        logger.error(f"Failed to save annotation: {e}")
        raise


