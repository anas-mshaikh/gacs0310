def process_video(client: anthropic.Anthropic,
                  sbert_model: SentenceTransformer,
                  video_row: pd.Series,
                  skip_existing: bool = True) -> List[Tuple[Scene, Annotation]]:
    """
    Process a single video through the full pipeline.

    Steps:
        1. Detect scene boundaries
        2. Extract keyframes from each scene
        3. Label keyframes using Claude Vision API
        4. Cache annotations

    Args:
        client: Initialized Anthropic API client
        sbert_model: Initialized SentenceTransformer model
        video_row: Row from the video manifest DataFrame
        skip_existing: Skip scenes that already have cached annotations

    Returns:
        List of (Scene, Annotation) tuples for successfully processed scenes
    """
    video_id = video_row['video_id']
    video_path = PROJECT_ROOT / video_row['file_path']

    logger.info(f"Processing video: {video_id}")
    print(f"\n{'='*70}")
    print(f"Processing: {video_id}")
    print(f"{'='*70}")

    # Check if video exists
    if not video_path.exists():
        logger.warning(f"Video not found at {video_path}")
        print("  ERROR: Video not found")
        return []

    # Step 1: Detect scenes
    print("\n[1/3] Detecting scenes...")
    scenes = detect_scenes(video_path, video_id)
    logger.info(f"Found {len(scenes)} scenes in {video_id}")
    print(f"  Found {len(scenes)} scenes")

    if not scenes:
        print("  No scenes detected, skipping video.")
        return []

    # Step 2: Extract keyframes
    print("\n[2/3] Extracting keyframes...")
    scenes = extract_keyframes(video_path, scenes, video_id)
    keyframe_count = sum(1 for s in scenes if s.keyframe_path)
    logger.info(f"Extracted {keyframe_count} keyframes for {video_id}")
    print(f"  Extracted {keyframe_count} keyframes")

    # Step 3: Label with Claude API
    print("\n[3/3] Labeling with Claude Vision API...")
    results = []

    for scene in tqdm(scenes, desc="Labeling", leave=False):
        if not scene.keyframe_path:
            continue

        keyframe_path = PROJECT_ROOT / scene.keyframe_path
        image_id = hashlib.md5(str(keyframe_path).encode()).hexdigest()[:12]

        # Check cache (resume capability)
        if skip_existing:
            cached = load_annotation(image_id)
            if cached:
                results.append((scene, cached))
                continue

        # Label keyframe
        annotation = label_keyframe(client, keyframe_path, video_id, scene.scene_id)

        if annotation:
            save_annotation(annotation)
            results.append((scene, annotation))

        time.sleep(API_RATE_LIMIT_DELAY)

    logger.info(f"Labeled {len(results)} scenes for {video_id}")
    print(f"  Labeled {len(results)} scenes")

    return results


def build_gacs_dataset(sbert_model: SentenceTransformer,
                       results: List[Tuple[Scene, Annotation]]) -> pd.DataFrame:
    """
    Build final GACS dataset with mood embeddings.

    Generates mood embeddings for each scene and combines all metadata
    into a single DataFrame suitable for machine learning workflows.

    Args:
        sbert_model: Initialized SentenceTransformer model
        results: List of (Scene, Annotation) tuples

    Returns:
        DataFrame with columns: image_id, video_id, scene_id, keyframe_path,
                                mood_vector, mood_words, style_words, object_words
    """
    logger.info("Building final GACS dataset with embeddings...")
    print("\n[4/4] Generating embeddings and building dataset...")

    dataset = []

    for scene, annotation in tqdm(results, desc="Building dataset", leave=False):
        # Generate mood embedding
        mood_vector = generate_mood_embedding(sbert_model, annotation.mood_words)

        entry = GACSEntry(
            image_id=annotation.image_id,
            video_id=annotation.video_id,
            scene_id=annotation.scene_id,
            keyframe_path=scene.keyframe_path or "",
            mood_vector=mood_vector,
            mood_words=', '.join(annotation.mood_words),
            style_words=', '.join(annotation.style_words),
            object_words=', '.join(annotation.object_words)
        )
        dataset.append(asdict(entry))

    df = pd.DataFrame(dataset)

    # Convert mood_vector list to string for CSV storage
    df['mood_vector'] = df['mood_vector'].apply(
        lambda x: ','.join(f"{v:.6f}" for v in x) if isinstance(x, list) else x
    )

    logger.info(f"Built dataset with {len(df)} entries")
    return df


