def detect_scenes(video_path: Path, video_id: str,
                  threshold: float = SCENE_THRESHOLD,
                  min_scene_len: int = MIN_SCENE_LENGTH) -> List[Scene]:
    """
    Detect scene boundaries in a video using PySceneDetect's ContentDetector.

    Scenes are detected by analyzing content changes between frames. Each
    scene is represented with frame numbers, timestamps, and duration.
    Scene metadata is saved to data/scenes/{video_id}/scene_metadata.json.

    Args:
        video_path: Path to the video file
        video_id: Unique identifier for the video
        threshold: Scene change detection threshold (0-100, default 27.0)
        min_scene_len: Minimum number of frames to consider a scene

    Returns:
        List of Scene objects ordered chronologically

    Raises:
        No exceptions raised; logs warnings and returns empty list on failure
    """
    if not video_path.exists():
        logger.warning(f"Video not found at {video_path}")
        return []

    try:
        # Open video and create scene manager
        video = open_video(str(video_path))
        scene_manager = SceneManager()
        scene_manager.add_detector(ContentDetector(
            threshold=threshold,
            min_scene_len=min_scene_len
        ))

        # Detect scenes
        scene_manager.detect_scenes(video)
        scene_list = scene_manager.get_scene_list()

        # Convert to Scene objects
        scenes = []
        for idx, (start, end) in enumerate(scene_list):
            scene_id = f"{video_id}_s{idx:04d}"
            scene = Scene(
                scene_id=scene_id,
                video_id=video_id,
                scene_index=idx,
                start_frame=start.get_frames(),
                end_frame=end.get_frames(),
                start_time=start.get_seconds(),
                end_time=end.get_seconds(),
                duration=end.get_seconds() - start.get_seconds()
            )
            scenes.append(scene)

        # Save scene metadata to JSON
        scene_dir = SCENES_DIR / video_id
        scene_dir.mkdir(parents=True, exist_ok=True)
        metadata_path = scene_dir / "scene_metadata.json"
        scene_dicts = [asdict(s) for s in scenes]
        with open(metadata_path, 'w') as f:
            json.dump(scene_dicts, f, indent=2)
        logger.info(f"Detected {len(scenes)} scenes in {video_id}, "
                    f"saved metadata to {metadata_path}")

        return scenes

    except Exception as e:
        logger.error(f"Error detecting scenes in {video_path}: {e}")
        return []


