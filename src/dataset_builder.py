def label_keyframe(client: anthropic.Anthropic,
                   image_path: Path,
                   video_id: str,
                   scene_id: str,
                   max_label_retries: int = 2) -> Optional[Annotation]:
    """
    Label a single keyframe with mood, style, and object words.

    Calls Claude Vision API three times (once per label type) and retries
    on validation failure. Labels are considered valid when they meet count
    specifications, but processing continues even if imperfect after retries.

    Args:
        client: Initialized Anthropic API client
        image_path: Path to the keyframe image
        video_id: Video identifier
        scene_id: Scene identifier
        max_label_retries: Maximum retry attempts on validation failure (default 2)

    Returns:
        Annotation object with labels, or None if all API calls failed
    """
    # Generate image_id from path hash
    image_id = hashlib.md5(str(image_path).encode()).hexdigest()[:12]

    for attempt in range(max_label_retries + 1):
        # Call Claude for each label type
        mood_response = call_claude_vision(client, image_path, MOOD_PROMPT)
        time.sleep(API_RATE_LIMIT_DELAY)

        style_response = call_claude_vision(client, image_path, STYLE_PROMPT)
        time.sleep(API_RATE_LIMIT_DELAY)

        object_response = call_claude_vision(client, image_path, OBJECT_PROMPT)

        if not all([mood_response, style_response, object_response]):
            logger.warning(f"Incomplete labeling for {image_path} "
                          f"(attempt {attempt + 1})")
            if attempt < max_label_retries:
                time.sleep(API_RATE_LIMIT_DELAY)
            continue

        # Parse responses
        mood_words = parse_comma_list(mood_response)
        style_words = parse_comma_list(style_response)
        object_words = parse_comma_list(object_response)

        # Validate label counts
        issues = validate_labels(mood_words, style_words, object_words)
        if not issues:
            # Valid labels, break out of retry loop
            break
        elif attempt < max_label_retries:
            logger.warning(f"Label validation failed (attempt {attempt + 1}): "
                          f"{issues}. Retrying...")
        else:
            logger.warning(f"Label validation still failing after "
                          f"{max_label_retries + 1} attempts: {issues}. "
                          f"Proceeding with partial labels.")

    # Return annotation even if imperfect after retries
    if not all([mood_response, style_response, object_response]):
        return None

    return Annotation(
        image_id=image_id,
        video_id=video_id,
        scene_id=scene_id,
        mood_words=mood_words,
        style_words=style_words,
        object_words=object_words,
        labeling_model=CLAUDE_MODEL,
        prompt_version=PROMPT_VERSION
    )


