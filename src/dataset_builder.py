def extract_keyframes(video_path: Path, scenes: List[Scene],
                      video_id: str) -> List[Scene]:
    """
    Extract mid-frame keyframes from each scene.

    For each scene, extracts the middle frame and saves it as a JPEG image
    to data/scenes/{video_id}/{scene_id}.jpg. Updates Scene objects with
    the keyframe_path attribute.

    Args:
        video_path: Path to the video file
        scenes: List of Scene objects with frame boundaries
        video_id: Video identifier for organizing output

    Returns:
        List of Scene objects with keyframe_path populated

    Raises:
        No exceptions raised; logs warnings if frames cannot be read
    """
    # Create output directory
    output_dir = SCENES_DIR / video_id
    output_dir.mkdir(parents=True, exist_ok=True)

    cap = cv2.VideoCapture(str(video_path))
    if not cap.isOpened():
        logger.error(f"Could not open video {video_path}")
        return scenes

    updated_scenes = []
    for scene in scenes:
        try:
            # Calculate mid-frame
            mid_frame = (scene.start_frame + scene.end_frame) // 2

            # Extract frame
            cap.set(cv2.CAP_PROP_POS_FRAMES, mid_frame)
            ret, frame = cap.read()

            if ret and frame is not None:
                # Save keyframe as {scene_id}.jpg
                keyframe_filename = f"{scene.scene_id}.jpg"
                keyframe_path = output_dir / keyframe_filename
                cv2.imwrite(str(keyframe_path), frame)

                # Store relative path from project root
                scene.keyframe_path = str(keyframe_path.relative_to(PROJECT_ROOT))
                logger.debug(f"Extracted keyframe for {scene.scene_id}")
            else:
                logger.warning(f"Failed to read frame {mid_frame} for {scene.scene_id}")

        except Exception as e:
            logger.warning(f"Error extracting keyframe for {scene.scene_id}: {e}")

        updated_scenes.append(scene)

    cap.release()
    extracted_count = sum(1 for s in updated_scenes if s.keyframe_path)
    logger.info(f"Extracted {extracted_count} keyframes for {video_id}")
    return updated_scenes


