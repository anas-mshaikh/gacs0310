# Embedding Generation (SBERT)
# ============================================================================

def generate_mood_embedding(sbert_model: SentenceTransformer,
                            mood_words: List[str]) -> List[float]:
    """
    Generate mood vector by averaging SBERT embeddings of mood words.

    Encodes each mood word using the SBERT model and computes the
    component-wise average to get a single 384-dimensional vector.

    Args:
        sbert_model: Initialized SentenceTransformer model
        mood_words: List of mood adjectives

    Returns:
        Averaged embedding vector as list of floats
    """
    if not mood_words:
        # Return zero vector of SBERT dimension
        return [0.0] * 384

    try:
        # Get embeddings for each word
        embeddings = sbert_model.encode(mood_words)

        # Average the embeddings
        mood_vector = np.mean(embeddings, axis=0)

        return mood_vector.tolist()
    except Exception as e:
        logger.error(f"Error generating mood embedding: {e}")
        return [0.0] * 384


