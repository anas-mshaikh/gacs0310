# Main Pipeline
# ============================================================================

def main(args):
    """
    Execute the full GACS dataset building pipeline.

    Args:
        args: Parsed command-line arguments
    """
    logger.info("="*70)
    logger.info("GACS Dataset Builder - Starting Pipeline")
    logger.info("="*70)

    # Validate configuration
    if not validate_config():
        logger.warning("Configuration validation issued warnings. Proceeding.")

    # Initialize API client
    try:
        client = anthropic.Anthropic()
        logger.info("Initialized Anthropic API client")
    except Exception as e:
        logger.error(f"Failed to initialize API client: {e}")
        return

    # Load SBERT model
    print("Loading SBERT model...")
    try:
        if GPU_AVAILABLE:
            sbert_model = SentenceTransformer(SBERT_MODEL, device=GPU_DEVICE)
            logger.info(f"Loaded SBERT model '{SBERT_MODEL}' on {GPU_DEVICE}")
        else:
            sbert_model = SentenceTransformer(SBERT_MODEL)
            logger.info(f"Loaded SBERT model '{SBERT_MODEL}' on CPU")
    except Exception as e:
        logger.error(f"Failed to load SBERT model: {e}")
        return

    # Load video manifest
    manifest_path = PROJECT_ROOT / args.input
    if not manifest_path.exists():
        logger.error(f"Manifest file not found: {manifest_path}")
        return

    try:
        manifest_df = pd.read_csv(manifest_path)
        # Normalize path separators using pathlib
        manifest_df['file_path'] = manifest_df['file_path'].apply(
            lambda p: str(Path(p))
        )
        logger.info(f"Loaded {len(manifest_df)} videos from {manifest_path}")
        print(f"Loaded {len(manifest_df)} videos from manifest")
    except Exception as e:
        logger.error(f"Failed to load manifest: {e}")
        return

    # Filter to downloaded videos
    available_videos = manifest_df[manifest_df.get('download_ok', True)]

    if QUICK_TEST_MODE or args.quick_test:
        available_videos = available_videos.head(QUICK_TEST_MAX_VIDEOS)
        logger.info(f"Quick-test mode: Processing {len(available_videos)} video(s)")

    if len(available_videos) == 0:
        logger.warning("No videos available to process")
        print("No videos available to process")
        return

    # Process all videos
    all_results = []
    print(f"\nProcessing {len(available_videos)} videos...\n")

    for idx, (_, row) in enumerate(available_videos.iterrows(), 1):
        if args.skip_labeling:
            # Skip labeling, use cached annotations only
            video_id = row['video_id']
            video_path = PROJECT_ROOT / row['file_path']
            logger.info(f"[{idx}/{len(available_videos)}] Scanning {video_id} "
                       f"for cached annotations (skip_labeling mode)")
            scenes = detect_scenes(video_path, video_id)
            scenes = extract_keyframes(video_path, scenes, video_id)

            for scene in scenes:
                if scene.keyframe_path:
                    keyframe_path = PROJECT_ROOT / scene.keyframe_path
                    image_id = hashlib.md5(str(keyframe_path).encode()).hexdigest()[:12]
                    cached = load_annotation(image_id)
                    if cached:
                        all_results.append((scene, cached))
        else:
            results = process_video(client, sbert_model, row, skip_existing=True)
            all_results.extend(results)

    print(f"\n{'='*70}")
    print("Scene Processing Complete!")
    print(f"{'='*70}")
    print(f"Total scenes processed: {len(all_results)}")
    logger.info(f"Scene processing complete: {len(all_results)} scenes")

    # Build final dataset
    if all_results:
        gacs_df = build_gacs_dataset(sbert_model, all_results)

        # Save to CSV
        output_path = EMBEDDINGS_DIR / args.output
        gacs_df.to_csv(output_path, index=False)

        print(f"\n{'='*70}")
        print("Dataset Saved")
        print(f"{'='*70}")
        print(f"Output: {output_path}")
        print(f"Total entries: {len(gacs_df)}")
        print(f"\nColumns: {list(gacs_df.columns)}")
        logger.info(f"Saved dataset to {output_path} ({len(gacs_df)} entries)")

        # Validate
        validate_dataset(gacs_df)

        # Optional visualization
        if args.visualize:
            print("\nGenerating visualization...")
            visualize_mood_embeddings(gacs_df)

    else:
        print("\nNo results to save. Check that videos are available.")
        logger.warning("No results to save. Pipeline produced 0 scenes.")

    logger.info("="*70)
    logger.info("GACS Dataset Builder - Pipeline Complete")
    logger.info("="*70)


